import { expect, test, type Page } from '@playwright/test'
import fs from 'node:fs'

const fill = async (page: Page, label: string, value: string) => { await page.getByLabel(label, { exact: true }).fill(value) }

test.describe('Homepage & shell', () => {
  test('renders branding, featured tools, categories and counts', async ({ page }) => {
    await page.goto('./')
    await expect(page.getByRole('heading', { name: 'DevPocket', level: 1 })).toBeVisible()
    await expect(page.getByText('104 developer utilities')).toBeVisible()
    await expect(page.getByRole('heading', { name: 'Featured' })).toBeVisible()
    await expect(page.getByTestId('card-json-formatter')).toBeVisible()
    for (const c of ['data', 'java', 'security', 'devops', 'text', 'datetime', 'visual', 'browser']) await expect(page.getByTestId(`cat-${c}`)).toBeVisible()
    await expect(page.getByTestId('cat-data')).toContainText('23 tools')
    await expect(page.getByTestId('cat-devops')).toContainText('16 tools')
  })

  test('home search filters tool cards and shows an empty state', async ({ page }) => {
    await page.goto('./')
    await page.getByTestId('home-search').fill('jwt')
    await expect(page.getByTestId('card-jwt-decoder')).toBeVisible()
    await expect(page.getByTestId('card-json-formatter')).toHaveCount(0)
    await page.getByTestId('home-search').fill('zzzzqqqq')
    await expect(page.getByText('No tools match')).toBeVisible()
  })

  test('command palette: keyboard shortcut, category filter and result navigation', async ({ page }) => {
    await page.goto('./')
    await expect(page.getByTestId('open-search')).toBeVisible()
    await page.keyboard.press('Control+k')
    const input = page.getByTestId('palette-input')
    await expect(input).toBeFocused()
    await input.fill('subnet')
    await expect(page.getByRole('option').first()).toContainText('CIDR')
    await page.keyboard.press('Enter')
    await expect(page).toHaveURL(/#\/tools\/cidr-calculator$/)
    await expect(page.getByTestId('tool-title')).toHaveText('CIDR / Subnet Calculator')
    await page.keyboard.press('/')
    await page.getByTestId('palette-input').fill('qqqqzzzz')
    await expect(page.getByText('No tools match')).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(page.getByTestId('palette-input')).toHaveCount(0)
  })

  test('navigation: sidebar, categories, all tools and back links work', async ({ page }) => {
    await page.goto('./')
    await page.getByRole('link', { name: /Encoding, Security/ }).first().click()
    await expect(page).toHaveURL(/#\/category\/security$/)
    await expect(page.getByRole('heading', { level: 1 })).toHaveText('Encoding, Security & HTTP')
    await expect(page.getByTestId('card-jwt-decoder')).toBeVisible()
    await page.getByTestId('card-jwt-decoder').getByRole('link').click()
    await expect(page.getByTestId('tool-title')).toHaveText('JWT Decoder')
    await page.getByRole('link', { name: 'All Tools' }).click()
    await expect(page.getByRole('heading', { name: 'All Tools' })).toBeVisible()
    await expect(page.locator('[data-testid^="card-"]')).toHaveCount(104)
    await page.getByRole('link', { name: 'Home', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'DevPocket', level: 1 })).toBeVisible()
  })

  test('theme switching applies and persists', async ({ page }) => {
    await page.goto('./')
    const html = page.locator('html')
    await page.getByTestId('theme-dark').click()
    await expect(html).toHaveClass(/dark/)
    await page.reload()
    await expect(html).toHaveClass(/dark/)
    await page.getByTestId('theme-light').click()
    await expect(html).not.toHaveClass(/dark/)
    await page.reload()
    await expect(html).not.toHaveClass(/dark/)
    await page.getByTestId('theme-system').click()
    await expect(page.getByTestId('theme-system')).toHaveAttribute('aria-checked', 'true')
  })

  test('favorites and recently used persist', async ({ page }) => {
    await page.goto('./')
    await page.getByRole('button', { name: 'Add JSON Formatter to favorites' }).click()
    await page.getByRole('link', { name: 'Favorites', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Favorites', level: 1 })).toBeVisible()
    await expect(page.getByTestId('card-json-formatter')).toBeVisible()
    await page.reload()
    await expect(page.getByTestId('card-json-formatter')).toBeVisible()
    await page.getByRole('button', { name: 'Remove JSON Formatter from favorites' }).click()
    await expect(page.getByText('No favorites yet')).toBeVisible()
    await page.goto('./#/tools/uuid-generator')
    await page.getByRole('link', { name: 'Recently Used' }).click()
    await expect(page.getByRole('heading', { name: 'Recently Used', level: 1 })).toBeVisible()
    await expect(page.getByTestId('card-uuid-generator')).toBeVisible()
    await page.goto('./#/tools/uuid-generator')
    await page.getByTestId('fav-toggle').click()
    await expect(page.getByTestId('fav-toggle')).toHaveAttribute('aria-pressed', 'true')
  })
})

test.describe('Tools', () => {
  test('JSON Formatter formats, minifies and reports errors', async ({ page }) => {
    await page.goto('./#/tools/json-formatter')
    await fill(page, 'Input', '{"b":1,"a":[1,2]}')
    await expect(page.getByLabel('Output', { exact: true })).toHaveValue('{\n  "b": 1,\n  "a": [\n    1,\n    2\n  ]\n}')
    await page.getByLabel('Mode').selectOption('minify')
    await expect(page.getByLabel('Output', { exact: true })).toHaveValue('{"b":1,"a":[1,2]}')
    await page.getByLabel('Mode').selectOption('format')
    await fill(page, 'Input', '{\n  "a": 1,\n  "b": }')
    await expect(page.getByRole('alert')).toContainText('line 3')
    await fill(page, 'Input', '{"x":1}')
    await expect(page.getByRole('status')).toContainText('Valid JSON')
    const dl = page.waitForEvent('download')
    await page.getByRole('button', { name: /Download/ }).click()
    expect((await dl).suggestedFilename()).toBe('formatted.json')
  })

  test('JSON Diff shows accurate counts and filters', async ({ page }) => {
    await page.goto('./#/tools/json-diff')
    await page.getByRole('button', { name: 'Load sample' }).click()
    const stat = (l: string) => page.getByText(l, { exact: true }).locator('xpath=following-sibling::div')
    await expect(stat('Added')).toHaveText('2')
    await expect(stat('Removed')).toHaveText('1')
    await expect(stat('Modified')).toHaveText('3')
    await expect(stat('Type changed')).toHaveText('1')
    await expect(page.getByTestId('diff-list').locator('tbody tr')).toHaveCount(7)
    await page.getByLabel('Filter by type').selectOption('typeChanged')
    await expect(page.getByTestId('diff-list').locator('tbody tr')).toHaveCount(1)
    await page.getByLabel('Filter by type').selectOption('all')
    await page.getByPlaceholder('Search path or value').fill('city')
    await expect(page.getByTestId('diff-list').locator('tbody tr')).toHaveCount(1)
  })

  test('Spring Properties Comparator: yaml vs yaml with masking and filters', async ({ page }) => {
    await page.goto('./#/tools/spring-properties-compare')
    await page.getByRole('button', { name: 'Sample' }).first().click()
    await page.getByRole('button', { name: 'Sample' }).nth(1).click()
    const table = page.getByTestId('compare-table')
    await expect(table).toBeVisible()
    const stat = (l: string) => page.getByText(l, { exact: true }).first().locator('xpath=following-sibling::div')
    await expect(stat('Added')).toHaveText('1'); await expect(stat('Removed')).toHaveText('2'); await expect(stat('Modified')).toHaveText('4'); await expect(stat('Unchanged')).toHaveText('2')
    // password is masked by default
    const pwRow = table.locator('tr', { hasText: 'spring.datasource.password' })
    await expect(pwRow).not.toContainText('s3cret'); await expect(pwRow).not.toContainText('different')
    await pwRow.getByRole('button', { name: 'Reveal value' }).click()
    await expect(pwRow).toContainText('s3cret')
    await page.getByTestId('filter-removed').click()
    await expect(table.locator('tbody tr')).toHaveCount(2)
    await page.getByTestId('filter-all').click()
    await page.getByPlaceholder('Search keys / values').fill('ddl-auto')
    await expect(table.locator('tbody tr')).toHaveCount(1)
  })

  test('Spring Properties Comparator: .properties compared with yaml', async ({ page }) => {
    await page.goto('./#/tools/spring-properties-compare')
    await page.getByLabel('Base (left)', { exact: true }).fill('server.port=8080\napp.name=demo\nspring.datasource.password=abc')
    await page.getByLabel('Target (right)', { exact: true }).fill('server:\n  port: 9090\napp:\n  name: demo\n')
    const table = page.getByTestId('compare-table')
    await expect(table.locator('tr[data-status="modified"]')).toHaveCount(1)
    await expect(table.locator('tr[data-status="unchanged"]')).toHaveCount(1)
    await expect(table.locator('tr[data-status="removed"]')).toHaveCount(1)
  })

  test('YAML Formatter formats and validates', async ({ page }) => {
    await page.goto('./#/tools/yaml-formatter')
    await fill(page, 'Input', 'a:\n    b:   1\n    c: [ 1,2 ]\n')
    await expect(page.getByLabel('Output', { exact: true })).toHaveValue('a:\n  b: 1\n  c:\n    - 1\n    - 2\n')
    await fill(page, 'Input', 'a: [1, 2\nb: 3')
    await expect(page.getByRole('alert')).toBeVisible()
  })

  test('JWT Decoder decodes claims and warns about signatures', async ({ page }) => {
    await page.goto('./#/tools/jwt-decoder')
    await expect(page.getByText('does not verify signatures')).toBeVisible()
    await page.getByRole('button', { name: 'Sample' }).click()
    await expect(page.getByText('Expired', { exact: true })).toBeVisible()
    await expect(page.getByText('Not verified', { exact: true })).toBeVisible()
    await expect(page.getByText('HS256').first()).toBeVisible()
    await expect(page.getByText('Ada Lovelace').first()).toBeVisible()
    await fill(page, 'Encoded token', 'abc.def')
    await expect(page.getByRole('alert')).toContainText('3 dot-separated')
  })

  test('UUID and password generators use secure output', async ({ page }) => {
    await page.goto('./#/tools/uuid-generator')
    await page.getByTestId('gen-uuid').click()
    const ids = await page.getByTestId('uuid-item').allTextContents()
    expect(ids).toHaveLength(5); for (const id of ids) expect(id).toMatch(/^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/)
    await page.goto('./#/tools/password-generator')
    const pw = await page.getByTestId('pw-item').first().textContent()
    expect(pw).toHaveLength(20)
  })

  test('Base64, hashing and regex tools compute real results', async ({ page }) => {
    await page.goto('./#/tools/base64')
    await fill(page, 'Input', 'Hello')
    await expect(page.getByLabel('Output', { exact: true })).toHaveValue('SGVsbG8=')
    await page.goto('./#/tools/hash-generator')
    await page.getByLabel('Text to hash').fill('abc')
    await expect(page.getByTestId('hash-SHA-256')).toHaveText('ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad')
    await page.goto('./#/tools/regex-playground')
    await expect(page.getByTestId('regex-matches').locator('tbody tr')).toHaveCount(2)
    await page.getByLabel('Regex pattern').fill('(a+)+$')
    await page.getByLabel('Test string').fill('a'.repeat(40) + '!')
    await expect(page.getByText('catastrophic backtracking')).toBeVisible({ timeout: 8000 })
  })
})

test.describe('GitHub Pages behaviour & privacy', () => {
  test('deep links work directly under the repository subpath and unknown routes show a 404 view', async ({ page }) => {
    await page.goto('./#/tools/json-diff')
    await expect(page.getByTestId('tool-title')).toHaveText('JSON Diff')
    await page.goto('./#/category/devops')
    await expect(page.getByRole('heading', { level: 1 })).toHaveText('DevOps & Config')
    await page.goto('./#/tools/does-not-exist')
    await expect(page.getByRole('heading', { name: 'Not found' })).toBeVisible()
    expect(new URL(page.url()).pathname).toBe('/DevPocket/')
  })

  test('all assets load from the subpath and no external requests are made', async ({ page }) => {
    const failed: string[] = [], external: string[] = []
    page.on('response', (r) => { if (r.status() >= 400) failed.push(`${r.status()} ${r.url()}`) })
    page.on('request', (r) => { const u = new URL(r.url()); if (u.origin !== 'http://localhost:4173' && !r.url().startsWith('data:') && !r.url().startsWith('blob:')) external.push(r.url()) })
    await page.goto('./#/tools/json-formatter')
    await expect(page.getByTestId('tool-title')).toBeVisible()
    expect(failed).toEqual([]); expect(external).toEqual([])
    const html = fs.readFileSync('dist/index.html', 'utf8')
    expect(html).toContain('/DevPocket/assets/')
  })

  test('service worker is registered for offline use', async ({ page }) => {
    await page.goto('./')
    const reg = await page.evaluate(async () => { const r = await navigator.serviceWorker.getRegistration(); return r?.scope ?? null })
    expect(reg).toBe('http://localhost:4173/DevPocket/')
  })

  test('sensitive tool input is not persisted to storage', async ({ page }) => {
    await page.goto('./#/tools/hmac')
    await page.getByLabel('Secret key').fill('super-secret-key-123')
    await page.getByLabel('Message').fill('payload-xyz')
    const dump = await page.evaluate(() => JSON.stringify({ l: { ...localStorage }, s: { ...sessionStorage } }))
    expect(dump).not.toContain('super-secret-key-123'); expect(dump).not.toContain('payload-xyz')
  })

  test('responsive: mobile layout shows the menu button and drawer navigation', async ({ page }) => {
    await page.setViewportSize({ width: 390, height: 800 })
    await page.goto('./')
    await page.getByRole('button', { name: 'Open menu' }).click()
    await page.getByRole('link', { name: /Favorites/ }).click()
    await expect(page.getByRole('heading', { name: 'Favorites' })).toBeVisible()
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth + 1)
    expect(overflow).toBe(false)
  })
})
